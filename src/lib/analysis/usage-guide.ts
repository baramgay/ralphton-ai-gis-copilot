/**
 * 활용 가이드 — 이 도구로 무엇을 어떻게 하는가.
 *
 * ## 왜 화면에 두는가
 *
 * 이 도구는 처음 여는 사람에게 「무엇을 물어도 되는지」를 알려 주지 않았다. 질의창은
 * 있는데 무엇을 넣어야 답이 나오는지는 시행착오로만 알 수 있었고, 그래서 대부분
 * 빠른 분석 버튼만 누르고 나머지 기능(지점 분석·지역 비교·교차·추세·내보내기)은
 * 있는 줄도 모르는 채 남았다.
 *
 * 문서를 따로 두는 길도 있지만, 별도 문서는 **화면과 갈라진다** — 라벨을 바꾸면 문서는
 * 그대로 남아 거짓말이 된다. 그래서 화면 안에 두고, 각 단계가 실제 라벨을 그대로 쓴다.
 *
 * 각 항목의 `caution`은 **그 기능에서 틀리기 쉬운 자리**다. 쓰는 법만 적으면 쓰기는
 * 하되 잘못 읽는다(순위를 볼 때 빠진 지역 수를 안 보는 것이 대표적이다).
 */

export type GuideStep = {
  /** 순서. 화면에 번호로 나온다. */
  order: number;
  title: string;
  /** 무엇을 하는 기능인가. 한 문장. */
  what: string;
  /** 어디를 눌러 어떻게 하는가. 실제 화면 라벨을 그대로 쓴다. */
  how: string[];
  /** 이 기능에서 틀리기 쉬운 자리. */
  caution?: string;
};

