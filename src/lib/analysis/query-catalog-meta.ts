/**
 * 부정을 반대 방향으로 바꿔 읽는다.
 *
 * "인구가 줄지 않은 동"이 **감소율이 가장 높은 곳**을 1위로 답하고 있었다(prod 실측) —
 * 정확히 반대다. `"인구가 줄"` 단서가 "인구가 줄지 않은"에 그대로 걸려서다. 부정은
 * 방향 낱말 바로 뒤에 붙으므로, 단서를 찾기 전에 그 자리를 반대말로 바꿔 둔다.
 *
 * 엄밀히는 "늘지 않은"에 보합도 들어가지만, 이 도구의 추세는 ±3%를 보합으로 보므로
 * 감소 쪽 정렬이 보합을 위쪽에 둔다. 반대 방향을 답하는 것보다 훨씬 가깝다.
 *
 * 결과는 단서 매칭에만 쓰고 화면에는 내보내지 않는다("감소하은 동"처럼 어색해진다).
 * 사용자에게는 각 도구의 안내가 어떻게 읽었는지 그대로 말해 준다.
 */
const NEGATED_DIRECTIONS: Array<[RegExp, string]> = [
  [/(늘어나|늘어|늘|증가하|증가|상승하|상승|오르|커지|많아지)지\s*않/g, "감소하"],
  [/(줄어들|줄어|줄|감소하|감소|하락하|하락|떨어지|작아지|적어지)지\s*않/g, "증가하"],
  [/안\s*(늘어나|늘어|늘|증가|상승|오르)/g, "감소하"],
  [/안\s*(줄어들|줄어|줄|감소|하락|떨어지)/g, "증가하"],
];

export function neutralizeNegatedDirection(text: string): string {
  let out = text;
  for (const [pattern, replacement] of NEGATED_DIRECTIONS) out = out.replace(pattern, replacement);
  return out;
}
